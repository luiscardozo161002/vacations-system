/* ==================================================================
   SISTEMA DE VACACIONES Y AVISOS DE AUSENCIA
   Script SQL para PostgreSQL: esquema + datos de prueba + consultas
   Convertido desde el script original en T-SQL (SQL Server)

   Diferencias principales respecto a la version SQL Server:
     - IDENTITY(1,1)           -> GENERATED BY DEFAULT AS IDENTITY
       ("BY DEFAULT" permite insertar IDs explicitos, igual que
       SET IDENTITY_INSERT ON en SQL Server; no se necesita ningun
       comando especial, solo recordar el setval() al final de cada
       tabla para que la secuencia siga despues de los IDs manuales).
     - NVARCHAR(n)              -> VARCHAR(n)
     - NVARCHAR(MAX)            -> TEXT / JSONB (segun el caso)
     - DATETIME2 / SYSUTCDATETIME() -> TIMESTAMPTZ / now()
     - BIT                      -> BOOLEAN
     - TINYINT                  -> SMALLINT
     - UNIQUEIDENTIFIER/NEWID() -> UUID / gen_random_uuid() (nativo desde PG 13)
     - columna PERSISTED        -> GENERATED ALWAYS AS (...) STORED
     - NVARCHAR(MAX) + CHECK ISJSON -> JSONB (ya garantiza JSON valido)
     - DATEADD/DATEDIFF/GETDATE -> operaciones con DATE/INTERVAL, age(), CURRENT_DATE, now()
     - CROSS APPLY (VALUES ..)  -> se elimina, el calculo se pone directo en el SELECT
     - DECLARE @variable        -> CTE "params" (sin usar funciones/PL-pgSQL)
     - TOP (n)                  -> LIMIT n
     - esquema "dbo"            -> se usa el esquema "public" por defecto

   Como ejecutarlo:
     1. Crea la base de datos (fuera de este script, porque CREATE DATABASE
        no puede ir en la misma sesion que el resto):
           createdb vacations_db
        o bien, conectado a la base "postgres":
           CREATE DATABASE vacations_db;
     2. Conectate a la base nueva (en psql: \c vacations_db) y corre el
        resto de este archivo.
   ================================================================== */


/* ==================================================================
   ORGANIZACIÓN
   ================================================================== */

CREATE TABLE company (
    company_id      INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    folio           VARCHAR(15)   NOT NULL UNIQUE,
    company_name    VARCHAR(150)  NOT NULL,
    company_branch  VARCHAR(100)  NULL,
    status          VARCHAR(20)   NOT NULL DEFAULT 'active' CHECK (status IN ('active','inactive')),
    created_at      TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_at      TIMESTAMPTZ   NOT NULL DEFAULT now()
);

CREATE TABLE shifts (
    shift_id        INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code            VARCHAR(20)   NOT NULL UNIQUE,
    shift_name      VARCHAR(100)  NOT NULL,
    number_days     SMALLINT      NOT NULL,
    created_at      TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_at      TIMESTAMPTZ   NOT NULL DEFAULT now()
);

CREATE TABLE shift_schedules (
    schedule_id     INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    shift_id        INT      NOT NULL REFERENCES shifts(shift_id),
    day_of_week     SMALLINT NOT NULL CHECK (day_of_week BETWEEN 1 AND 7),
    is_working_day  BOOLEAN  NOT NULL DEFAULT TRUE,
    check_in_time   TIME(0)  NULL,
    check_out_time  TIME(0)  NULL,
    CONSTRAINT UQ_shift_schedules UNIQUE (shift_id, day_of_week)
);

CREATE TABLE departments (
    department_id        INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id            INT NOT NULL REFERENCES company(company_id),
    code                   VARCHAR(20)   NOT NULL,
    department_name       VARCHAR(150)  NOT NULL,
    manager_employee_id   INT NULL,
    status                 VARCHAR(20) NOT NULL DEFAULT 'active' CHECK (status IN ('active','inactive')),
    created_at             TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at             TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT UQ_departments_company_code UNIQUE (company_id, code)
);

CREATE TABLE employees (
    employee_id       INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    department_id     INT NOT NULL REFERENCES departments(department_id),
    shift_id          INT NOT NULL REFERENCES shifts(shift_id),
    folio             VARCHAR(10)   NOT NULL,
    employee_number   VARCHAR(20)   NOT NULL UNIQUE,
    employee_name     VARCHAR(150)  NOT NULL,
    start_date        DATE          NOT NULL,
    status            VARCHAR(20)   NOT NULL DEFAULT 'active' CHECK (status IN ('active','inactive')),
    created_at        TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_at        TIMESTAMPTZ   NOT NULL DEFAULT now()
);

ALTER TABLE departments
