-- 1) Antigüedad y días de vacaciones que le corresponden HOY a cada empleado
SELECT
    e.employee_id,
    e.employee_number,
    e.employee_name,
    e.start_date,
    EXTRACT(YEAR FROM age(CURRENT_DATE, e.start_date))::int AS years_of_service,
    r.vacation_days AS days_vacations
FROM employees e
LEFT JOIN vacation_accrual_rules r
    ON EXTRACT(YEAR FROM age(CURRENT_DATE, e.start_date))::int BETWEEN r.years_from AND COALESCE(r.years_to, 999)
   AND r.status = 'active'
   AND r.effective_year = (SELECT MAX(effective_year) FROM vacation_accrual_rules WHERE effective_year <= EXTRACT(YEAR FROM CURRENT_DATE)::int)
ORDER BY years_of_service DESC;


-- 2) Saldo de vacaciones del periodo actual por empleado, con empresa y departamento.
SELECT
    c.company_name,
    d.department_name,
    e.employee_name,
    ve.period_year,
    ve.years_of_service,
    ve.total_days,
    ve.used_days,
    ve.remaining_days
FROM vacation_entitlements ve
JOIN employees e   ON e.employee_id = ve.employee_id
JOIN departments d ON d.department_id = e.department_id
JOIN company c     ON c.company_id = d.company_id
WHERE ve.period_year = EXTRACT(YEAR FROM CURRENT_DATE)::int
ORDER BY c.company_name, d.department_name, e.employee_name;


-- 3) Avisos pendientes de aprobación, con datos del solicitante y el motivo.
SELECT
    n.notice_id,
    e.employee_name,
    d.department_name,
    r.description AS motivo,
    n.absence_start_date,
    n.absence_end_date,
    n.request_date
FROM notices n
JOIN employees e   ON e.employee_id = n.employee_id
JOIN departments d ON d.department_id = e.department_id
JOIN reasons r     ON r.reason_id = n.reason_id
WHERE n.status = 'pending'
ORDER BY n.request_date;


-- 4) ¿El empleado tiene días suficientes para solicitar un rango de vacaciones?
--    Ejemplo: employee_id = 4, solicitando 6 días.
--    (los "parámetros" se simulan con un CTE, sin usar DECLARE ni funciones)
WITH params AS (
    SELECT 4 AS employee_id, 6 AS dias_solicitados
)
SELECT
    e.employee_name,
    ve.remaining_days AS dias_disponibles,
    p.dias_solicitados,
    CASE WHEN COALESCE(ve.remaining_days,0) >= p.dias_solicitados
         THEN 'Saldo suficiente' ELSE 'Saldo insuficiente' END AS resultado
FROM params p
JOIN employees e ON e.employee_id = p.employee_id
LEFT JOIN vacation_entitlements ve
    ON ve.employee_id = e.employee_id AND ve.period_year = EXTRACT(YEAR FROM CURRENT_DATE)::int;


-- 5) Permisos efectivos de un usuario (para validar RBAC en el backend).
--    Ejemplo: username = 'r.jimenez'.
SELECT
    u.username,
    ro.role_code,
    p.permission_code
FROM users u
JOIN roles ro            ON ro.role_id = u.role_id
JOIN role_permissions rp ON rp.role_id = ro.role_id
JOIN permissions p       ON p.permission_id = rp.permission_id
WHERE u.username = 'r.jimenez'
ORDER BY p.permission_code;


-- 6) Empleados por departamento y empresa, con su turno y antigüedad actual.
SELECT
    c.company_name,
    d.department_name,
    e.employee_name,
    e.employee_number,
    s.shift_name,
    e.start_date,
    EXTRACT(YEAR FROM age(CURRENT_DATE, e.start_date))::int AS antiguedad_anios
FROM employees e
JOIN departments d ON d.department_id = e.department_id
JOIN company c     ON c.company_id = d.company_id
JOIN shifts s       ON s.shift_id = e.shift_id
ORDER BY c.company_name, d.department_name, e.employee_name;


-- 7) Quién es el jefe de cada departamento (y a qué empresa pertenece).
SELECT
    c.company_name,
    d.department_name,
    mgr.employee_name AS jefe_departamento
FROM departments d
JOIN company c           ON c.company_id = d.company_id
LEFT JOIN employees mgr  ON mgr.employee_id = d.manager_employee_id
ORDER BY c.company_name, d.department_name;


