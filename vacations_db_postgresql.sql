CREATE TABLE vacation_accrual_rules (
    rule_id          INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    years_from        INT NOT NULL,
    years_to          INT NULL,
    vacation_days     INT NOT NULL,
    effective_year    INT NOT NULL,
    status            VARCHAR(20) NOT NULL DEFAULT 'active' CHECK (status IN ('active','inactive')),
    created_at        TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT CK_vacation_rules_range CHECK (years_to IS NULL OR years_to >= years_from)
);

CREATE TABLE vacation_entitlements (
    entitlement_id     INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id         INT NOT NULL REFERENCES employees(employee_id),
    period_year         INT NOT NULL,
    years_of_service    INT NOT NULL,
    rule_id             INT NOT NULL REFERENCES vacation_accrual_rules(rule_id),
    total_days          INT NOT NULL,
    used_days           INT NOT NULL DEFAULT 0,
    remaining_days      INT GENERATED ALWAYS AS (total_days - used_days) STORED,
    generated_at         TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT UQ_vacation_entitlements UNIQUE (employee_id, period_year)
);


