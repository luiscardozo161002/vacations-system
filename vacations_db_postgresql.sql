CREATE TABLE roles (
    role_id       INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    role_code     VARCHAR(30)   NOT NULL UNIQUE,
    description   VARCHAR(150)  NOT NULL,
    status        VARCHAR(20)   NOT NULL DEFAULT 'active' CHECK (status IN ('active','inactive'))
);

CREATE TABLE permissions (
    permission_id     INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    permission_code   VARCHAR(60)   NOT NULL UNIQUE,
    description        VARCHAR(150)  NOT NULL
);

CREATE TABLE role_permissions (
    role_id         INT NOT NULL REFERENCES roles(role_id),
    permission_id   INT NOT NULL REFERENCES permissions(permission_id),
    CONSTRAINT PK_role_permissions PRIMARY KEY (role_id, permission_id)
);

CREATE TABLE users (
    user_id                 INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id             INT NULL UNIQUE REFERENCES employees(employee_id),
    role_id                 INT NOT NULL REFERENCES roles(role_id),
    username                VARCHAR(50)  NOT NULL UNIQUE,
    email                   VARCHAR(120) NOT NULL UNIQUE,
    password_hash           VARCHAR(255) NOT NULL,
    status                  VARCHAR(20)  NOT NULL DEFAULT 'active' CHECK (status IN ('active','inactive','locked')),
    mfa_enabled             BOOLEAN      NOT NULL DEFAULT FALSE,
    mfa_secret              VARCHAR(255) NULL,
    failed_login_attempts   INT          NOT NULL DEFAULT 0,
    locked_until            TIMESTAMPTZ  NULL,
    last_login_at           TIMESTAMPTZ  NULL,
    last_login_ip           VARCHAR(45)  NULL,
    created_at              TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at              TIMESTAMPTZ  NOT NULL DEFAULT now()
);

CREATE TABLE user_sessions (
    session_id            UUID NOT NULL DEFAULT gen_random_uuid() PRIMARY KEY,
    user_id                INT NOT NULL REFERENCES users(user_id),
    refresh_token_hash     VARCHAR(255) NOT NULL,
    ip_address             VARCHAR(45)  NULL,
    user_agent             VARCHAR(255) NULL,
    issued_at              TIMESTAMPTZ  NOT NULL DEFAULT now(),
    expires_at             TIMESTAMPTZ  NOT NULL,
    revoked_at             TIMESTAMPTZ  NULL
);

CREATE TABLE password_reset_tokens (
    token_id       INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id         INT NOT NULL REFERENCES users(user_id),
    token_hash      VARCHAR(255) NOT NULL,
    expires_at      TIMESTAMPTZ  NOT NULL,
    used_at         TIMESTAMPTZ  NULL,
    created_at      TIMESTAMPTZ  NOT NULL DEFAULT now()
);

CREATE TABLE auth_audit_log (
    log_id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id        INT NULL REFERENCES users(user_id),
    event_type     VARCHAR(40)  NOT NULL,
    ip_address     VARCHAR(45)  NULL,
    user_agent     VARCHAR(255) NULL,
    metadata       JSONB NULL,
    created_at     TIMESTAMPTZ  NOT NULL DEFAULT now()
);


/* ==================================================================
   VACACIONES
