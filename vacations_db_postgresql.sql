-- 9) Resumen de avisos por motivo y estatus en el año actual (tipo reporte).
SELECT
    r.description AS motivo,
    n.status,
    COUNT(*) AS total_avisos
FROM notices n
JOIN reasons r ON r.reason_id = n.reason_id
WHERE EXTRACT(YEAR FROM n.request_date) = EXTRACT(YEAR FROM CURRENT_DATE)
GROUP BY r.description, n.status
ORDER BY r.description, n.status;


-- 10) Horario completo de un turno (para pantallas de asistencia).
SELECT
    sh.shift_name,
    ss.day_of_week,
    ss.is_working_day,
    ss.check_in_time,
    ss.check_out_time
FROM shift_schedules ss
JOIN shifts sh ON sh.shift_id = ss.shift_id
WHERE sh.code = 'OPERACIONES'
ORDER BY ss.day_of_week;
