CREATE TABLE notices (
    notice_id                INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id               INT NOT NULL REFERENCES employees(employee_id),
    reason_id                 INT NOT NULL REFERENCES reasons(reason_id),
    approved_by               INT NULL REFERENCES users(user_id),
    status                    VARCHAR(20) NOT NULL DEFAULT 'pending'
                                   CHECK (status IN ('pending','approved','rejected','cancelled')),
    absence_start_date        DATE NOT NULL,
    absence_end_date          DATE NOT NULL,
    absence_start_time        TIME(0) NULL,
    absence_end_time          TIME(0) NULL,
    remaining_days            INT NULL,
    remaining_hours           INT NULL,
    remarks                   VARCHAR(255) NULL,
    request_date               TIMESTAMPTZ NOT NULL DEFAULT now(),
    approved_at                TIMESTAMPTZ NULL,
    CONSTRAINT CK_notices_dates CHECK (absence_end_date >= absence_start_date)
);


